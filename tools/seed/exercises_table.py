"""UnFat exercise selection.

STRENGTH rows pick exercises from free-exercise-db (yuhonas/free-exercise-db,
Unlicense) by their id. English name, muscles and equipment come from that
dataset (mapped to UnFat enums in generate.py); only the Turkish name, the MET
value and an optional primary-muscle override are UnFat's own.

CARDIO rows are activities. Where free-exercise-db has a matching entry its id
is used; otherwise the English name follows the 2024 Adult Compendium of
Physical Activities wording.

MET values (2024 Adult Compendium of Physical Activities):
  3.5  resistance training, multiple exercises, light/moderate (02054) - isolation
  3.8  calisthenics, moderate (02020) - push-ups, sit-ups, crunches, planks
  5.0  squats / deadlifts / lunges, moderate-vigorous (02052) - big compound lifts
  6.0  free weights, vigorous (02050) - Olympic lifts, swings, thrusters
  8.0  calisthenics vigorous (02022) - pull-up/dip family is kept at 3.8-5.0
Cardio METs are listed per activity below.

Row format
  S(fedb_id, name_tr, met, primary=None)
  C(fedb_id_or_None, name_tr, name_en, equipment, met)
"""
